# 升级张数：段 → **期望张数**（无 A20 实测，沿用上游 A0 实测取整）
UPGRADES = (0, 2, 4, 6, 8, 10)

# 删初始牌：段 → **期望张数**（末段 = 10 − A20 实测初始牌 4.95）
REMOVALS = (0.0, 1.7, 1.7, 3.4, 3.4, 5.05)


def stage(floor_num):
    """floor → 段号 0..5（每幕对半切；floor 越界只夹下界，上界留给 act4）。"""
    f = max(int(floor_num), 0)
    return sum(1 for edge in STAGE_EDGES if f >= edge)


def how_many_to_add(floor_num):
    """要**追加**的牌：`(白, 蓝, 金, 咒, 特)` 期望张数（调用方随机取整）。"""
    return DECK[stage(floor_num)]


def how_many_to_upgrade(floor_num, rng):
    """该段要随机升级的张数：`UPGRADES[段]`（**期望值** → `draw_poisson`）。"""
    return draw_poisson(UPGRADES[stage(floor_num)], rng)


def how_many_to_remove(floor_num, rng):
    """该段要再删的初始牌张数：`REMOVALS[段]`（**期望值** → `draw_poisson`）。"""
    return draw_poisson(REMOVALS[stage(floor_num)], rng)


def relics_of(tier, floor_num):
    """该段该**档**的遗物件数：`RELICS[档][段]`（**期望值** → `draw_poisson`）。

    `tier` 取 `"common" / "uncommon" / "rare" / "boss" / "shop" / "special"`。
    """
    return RELICS[tier][stage(floor_num)]


def relic_total(floor_num):
    """该段应有的遗物**总数**（含引擎给的初始 Burning Blood）。

    从分档表推（单一来源）：`1 + Σ_档 relics_of(档, 段)` ⇒ `1.31 → 3.94 → 8.52 →
    11.87 → 16.68 → 21.00`。注意末段 21.0 比 A20 实测 20.70 多 0.3 —— 实测里初始那件只有
    0.71 件（有 Boss 遗物换初始的情形），而引擎给的初始遗物我们不会去删。
    """
    i = stage(floor_num)
    return 1.0 + sum(RELICS[t][i] for t in RELICS)


def draw_poisson(mean, rng):
    """期望值 → **泊松抽样**（Knuth），返回 Python `int`；`mean ≤ 0` ⇒ 恒 0。

    表里只有期望值一个数，宽度就跟着量走（泊松 σ = √mean）⇒ 不用另配 σ，
    段与段之间也不是硬台阶（相邻段分布重叠）。**精确保均值**、天然非负。
    不用 `normalvariate` + 四舍五入：下限 0 的截断正态会把低均值档抬高（0.3 → 0.372，+24%）。
    ⚠️ 只从 `rng.random()` 取数 ⇒ 仍是调用方那套 `random.Random`，同 seed 逐位可复现。
    """
    if mean <= 0:
        return 0
    limit = math.exp(-mean)
    k, p = 0, 1.0
    while True:
        k += 1
        p *= rng.random()
        if p <= limit:
            return k - 1
