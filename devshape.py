# 段间形状 = 遗物总数阶梯（扣掉初始那件）等比缩放到各档终点 —— **没有逐层实测**。
# ⚠️ Boss 在真实游戏里只在幕末三选一，这里的段间形状是按总数摊的 ⇒ 中段会早出一两件。
