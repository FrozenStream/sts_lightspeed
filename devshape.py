import math

# ── 6 段（= 每幕上/下半；act4 归第 6 段）。下面是各段起点（第 1 段固定 0）。──
STAGE_EDGES = (9, 17, 26, 34, 41)
STAGES = len(STAGE_EDGES) + 1

# 追加牌 (白=COMMON, 蓝=UNCOMMON, 金=RARE, 咒=CURSE, 特=SPECIAL) 的**累计**期望张数。
# 白/蓝/金末段 = A20 实测（5.63 / 9.71 / 4.81）。
# ⚠️ 咒末段 0.8 是**刻意超采样**，不是实测：实测 A20 胜局只有 0.13 张/局。
#   理由 = 覆盖优先于保真 —— 0.13 意味着 ~8 局才见 1 张，网络几乎见不到死牌，
#   学不出「牌组里多一张废牌 ⇒ 值更低」。代价：牌组比真实 A20 胜局脏 ~0.7 张/局。
# ⚠️ 特末段 0.95 = A20 实测「特殊 1.51」减去引擎按进阶等级给的 `ASCENDERS_BANE`
#   （当前 `ASCENSION_RANGE = (0, 20)` ⇒ 出现率 0.56）—— **改抽法要同步改这列**。
